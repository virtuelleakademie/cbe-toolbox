import { readFile, readdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { LINUX_SIZES } from "./icon-pipeline.mjs";

const appRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

async function onlyDesktopFile(extractedRoot) {
  const names = (await readdir(extractedRoot)).filter((name) => name.endsWith(".desktop"));
  if (names.length !== 1) throw new Error(`Expected one AppImage desktop file, found ${names.length}`);
  return path.join(extractedRoot, names[0]);
}

/** Inspect an extracted AppImage payload against the committed generated bytes. */
export async function inspectLinuxIconArtifact(extractedRoot, buildResources = path.join(appRoot, "buildResources")) {
  const desktop = await readFile(await onlyDesktopFile(extractedRoot), "utf8");
  const iconName = desktop.match(/^Icon=(.+)$/m)?.[1]?.trim();
  if (!iconName || iconName.toLowerCase().includes("electron"))
    throw new Error("Desktop metadata has no branded icon name");
  if (!/^Name=CBE Toolbox$/m.test(desktop) || !/^Categories=.*Education/m.test(desktop)) {
    throw new Error("Desktop metadata is missing the CBE Toolbox identity/category");
  }

  for (const size of LINUX_SIZES) {
    const packaged = await readFile(
      path.join(extractedRoot, "usr/share/icons/hicolor", `${size}x${size}`, "apps", `${iconName}.png`)
    );
    const generated = await readFile(path.join(buildResources, "icons", `${size}x${size}.png`));
    if (!packaged.equals(generated)) throw new Error(`Packaged Linux icon differs at ${size}x${size}`);
  }
  const runtime = await readFile(path.join(extractedRoot, "resources/icon.png"));
  const generatedRuntime = await readFile(path.join(buildResources, "icon.png"));
  if (!runtime.equals(generatedRuntime)) throw new Error("Packaged runtime icon differs from buildResources/icon.png");
  return { iconName, sizes: [...LINUX_SIZES] };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const extractedRoot = path.resolve(process.argv[2] ?? path.join(appRoot, "release/squashfs-root"));
  try {
    const result = await inspectLinuxIconArtifact(extractedRoot);
    console.log(`Verified AppImage icon ${result.iconName} at ${result.sizes.join(", ")} px plus runtime PNG.`);
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  }
}
